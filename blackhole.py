    t = frame / FPS

    # Smooth continuous inward spiral.
    # Particles are recycled at the outside to keep
    # the scene full throughout the animation.
    phase = (
        initial_radius / OUTER_RADIUS
        + infall_speed * t * 0.70
    ) % 1.0

    radius = (
        OUTER_RADIUS
        - phase * (OUTER_RADIUS - INNER_RADIUS)
    )

    # Faster orbital angular motion near the center
    angle = (
        initial_theta
        + rotation_speed * t / np.maximum(radius, 0.58) ** 0.75
        + 2.2 * phase
    )

    x = radius * np.cos(angle)
    y = radius * np.sin(angle)

    particles.set_offsets(np.column_stack((x, y)))

    # Shift the trails and insert the newest particle positions
    trail_x[:] = np.roll(trail_x, 1, axis=0)
    trail_y[:] = np.roll(trail_y, 1, axis=0)

    trail_x[0] = x
    trail_y[0] = y

    valid = np.isfinite(trail_x) & np.isfinite(trail_y)

    trail_scatter.set_offsets(
        np.column_stack((trail_x[valid], trail_y[valid]))
    )

    # Rotate the inner disk faster than the outer halo
    disk_angle_now = disk_theta + 0.85 * t
    disk_x = disk_radius * np.cos(disk_angle_now)
    disk_y = disk_radius * np.sin(disk_angle_now)

    disk.set_offsets(np.column_stack((disk_x, disk_y)))

    # Rotate the halo dust slowly for layered motion
    halo_angle_now = halo_theta + 0.12 * t
    halo_x = halo_radius * np.cos(halo_angle_now)
    halo_y = halo_radius * np.sin(halo_angle_now)

    halo.set_offsets(np.column_stack((halo_x, halo_y)))

    # Subtle pulse around the event horizon
    edge.set_linewidth(1.3 + 0.45 * np.sin(3.0 * t))
    outer_glow.set_alpha(0.18 + 0.08 * (1 + np.sin(2.0 * t)))

    return (
        particles,
        trail_scatter,
        disk,
        halo,
        edge,
        outer_glow,
    )

