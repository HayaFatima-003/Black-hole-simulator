def derivatives(state, active_mask):
    """Return dx/dt, dy/dt, dvx/dt, dvy/dt."""
    px, py, pvx, pvy = state

    radius_sq = px**2 + py**2

    # Prevent singular acceleration at the central object
    safe_radius_sq = np.maximum(radius_sq, r_capture**2)
    inv_r3 = safe_radius_sq ** (-1.5)

    ax = -mu * px * inv_r3
    ay = -mu * py * inv_r3

    # Captured particles are frozen
    mask = active_mask.astype(float)

    return (
        pvx * mask,
        pvy * mask,
        ax * mask,
        ay * mask
    )


def rk4_step(x, y, vx, vy, dt, active_mask):
    """Advance all particles by one RK4 time step."""
    state = (x, y, vx, vy)

    def add_scaled(s, k, scale):
        return tuple(a + scale * b for a, b in zip(s, k))

    k1 = derivatives(state, active_mask)
    k2 = derivatives(add_scaled(state, k1, dt / 2), active_mask)
    k3 = derivatives(add_scaled(state, k2, dt / 2), active_mask)
    k4 = derivatives(add_scaled(state, k3, dt), active_mask)

    result = tuple(
        a + dt / 6 * (b1 + 2*b2 + 2*b3 + b4)
        for a, b1, b2, b3, b4
        in zip(state, k1, k2, k3, k4)
    )

    return result


