# -------------------------
# 2. 3D COORDINATE TRANSFORM
# -------------------------
# Rotate the disk around the X-axis.
# Local disk coordinates (u, v) become 3D (x, y, z).

def disk_to_3d(u, v, w=0.0):
    u, v, w = np.broadcast_arrays(
        np.asarray(u, dtype=float),
        np.asarray(v, dtype=float),
        np.asarray(w, dtype=float)
    )

    x = u
    y = v * cos_t - w * sin_t
    z = v * sin_t + w * cos_t

    return x, y, z


